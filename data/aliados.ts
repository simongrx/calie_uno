// SOLICITUD DE ALIANZA
export interface SolicitudAlianza {
  nombre: string;
  email: string;
  telefono: string;
  organizacion: string;
  categoria: string;
  descripcion: string;
  nivelInteres: 'plata' | 'oro' | 'platino';
  website?: string;
  aceptaTerminos: boolean;
}

export const validarSolicitudAlianza = (solicitud: Partial<SolicitudAlianza>): boolean => {
  return !!(
    solicitud.nombre &&
    solicitud.email &&
    solicitud.telefono &&
    solicitud.organizacion &&
    solicitud.categoria &&
    solicitud.descripcion &&
    solicitud.descripcion.length >= 50 &&
    solicitud.nivelInteres &&
    solicitud.aceptaTerminos
  );
};

// PROCESAMIENTO DE SOLICITUD
export const procesarSolicitudAlianza = (solicitud: SolicitudAlianza) => {
  if (!validarSolicitudAlianza(solicitud)) {
    return {
      exito: false,
      mensaje: 'Datos incompletos o inválidos'
    };
  }

  return {
    exito: true,
    mensaje: 'Solicitud recibida correctamente',
    id: `solicitud-${Date.now()}`,
    estado: 'pendiente-revision',
    fecha: new Date().toISOString()
  };
};

