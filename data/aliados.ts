// FILTRO AVANZADO
export interface FiltroAliados {
  categoria?: string;
  busqueda?: string;
  conContacto?: boolean;
}

export const filtrarAliados = (filtro: FiltroAliados) => {
  return aliados.filter(a => {
    if (filtro.categoria && a.categoria !== filtro.categoria) return false;
    if (filtro.conContacto === true && !a.contacto) return false;
    if (filtro.busqueda) {
      const busquedaLower = filtro.busqueda.toLowerCase();
      return (
        a.nombre.toLowerCase().includes(busquedaLower) ||
        a.descripcion.toLowerCase().includes(busquedaLower)
      );
    }
    return true;
  });
};

