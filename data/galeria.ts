// FILTRO AVANZADO
export interface FiltroGaleria {
  pilar?: string;
  ruta?: string;
  evento?: string;
  busqueda?: string;
}

export const filtrarGaleria = (filtro: FiltroGaleria) => {
  return galeria.filter(img => {
    if (filtro.pilar && img.pilar !== filtro.pilar) return false;
    if (filtro.ruta && img.ruta !== filtro.ruta) return false;
    if (filtro.evento && img.evento !== filtro.evento) return false;
    if (filtro.busqueda) {
      const busquedaLower = filtro.busqueda.toLowerCase();
      return (
        img.titulo.toLowerCase().includes(busquedaLower) ||
        img.alt.toLowerCase().includes(busquedaLower)
      );
    }
    return true;
  });
};

