// FUNCIÓN PARA OBTENER IMAGEN SIGUIENTE
export const obtenerImagenSiguiente = (imagenId: string, filtro?: FiltroGaleria) => {
  const imagenes = filtro ? filtrarGaleria(filtro) : galeria;
  const indiceActual = imagenes.findIndex(img => img.id === imagenId);
  if (indiceActual === -1 || indiceActual === imagenes.length - 1) return imagenes[0];
  return imagenes[indiceActual + 1];
};

// FUNCIÓN PARA OBTENER IMAGEN ANTERIOR
export const obtenerImagenAnterior = (imagenId: string, filtro?: FiltroGaleria) => {
  const imagenes = filtro ? filtrarGaleria(filtro) : galeria;
  const indiceActual = imagenes.findIndex(img => img.id === imagenId);
  if (indiceActual === -1 || indiceActual === 0) return imagenes[imagenes.length - 1];
  return imagenes[indiceActual - 1];
};

// FUNCIÓN PARA OBTENER ÍNDICE DE IMAGEN
export const obtenerIndiceImagen = (imagenId: string, filtro?: FiltroGaleria): number => {
  const imagenes = filtro ? filtrarGaleria(filtro) : galeria;
  return imagenes.findIndex(img => img.id === imagenId) + 1;
};

