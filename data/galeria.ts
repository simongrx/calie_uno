// FUNCIÓN PARA ORGANIZAR EN MASONRY
export const organizarEnMasonry = (imagenes: ImagenGaleria[]) => {
  return imagenes.sort((a, b) => {
    // Priorizar imágenes grandes (4x3 o 3x4)
    const pesoA = a.ancho === 4 || a.alto === 4 ? 1 : 0;
    const pesoB = b.ancho === 4 || b.alto === 4 ? 1 : 0;
    return pesoB - pesoA;
  });
};

