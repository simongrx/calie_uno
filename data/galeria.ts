// FUNCIÓN PARA EXPORTAR GALERÍA
export const exportarGaleria = (formato: 'json' | 'csv' = 'json') => {
  if (formato === 'json') {
    return JSON.stringify(galeria, null, 2);
  }
  // CSV
  const headers = ['ID', 'Título', 'Pilar', 'Ruta', 'Evento'];
  const rows = galeria.map(img => [
    img.id,
    img.titulo,
    img.pilar,
    img.ruta || '-',
    img.evento || '-'
  ]);
  return [headers, ...rows].map(row => row.join(',')).join('\n');
};

// FUNCIÓN PARA VALIDAR IMAGEN
export const validarImagen = (imagen: Partial<ImagenGaleria>): boolean => {
  return !!(
    imagen.id &&
    imagen.src &&
    imagen.alt &&
    imagen.titulo &&
    imagen.pilar &&
    imagen.ancho &&
    imagen.alto
  );
};

// FUNCIÓN PARA CREAR MINIATURA
export const crearMiniatura = (imagen: ImagenGaleria, ancho: number = 300) => {
  const alto = Math.round((ancho / imagen.ancho) * imagen.alto);
  return {
    ...imagen,
    ancho,
    alto,
    srcMini: imagen.src.replace('.webp', `-${ancho}w.webp`)
  };
};

