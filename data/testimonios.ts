export const generarRespuesta = (plantillaId: string, datos: any) => {
  const plantilla = plantillasRespuesta.find(p => p.id === plantillaId);
  if (!plantilla) return '';
  
  let respuesta = plantilla.template;
  Object.keys(datos).forEach(key => {
    respuesta = respuesta.replace(`{${key}}`, datos[key]);
  });
  return respuesta;
};

// ANÁLISIS DE SENTIMIENTO (para futuro)
export const analizarSentimiento = (texto: string): 'positivo' | 'neutral' | 'negativo' => {
  const palabrasPositivas = ['increíble', 'hermoso', 'excelente', 'perfecto', 'maravilloso', 'recomendado'];
  const palabrasNegativas = ['malo', 'horrible', 'decepción', 'problema', 'pésimo'];
  
  const textoLower = texto.toLowerCase();
  const positivos = palabrasPositivas.filter(p => textoLower.includes(p)).length;
  const negativos = palabrasNegativas.filter(p => textoLower.includes(p)).length;
  
  if (positivos > negativos) return 'positivo';
  if (negativos > positivos) return 'negativo';
  return 'neutral';
};

// NUBE DE PALABRAS
export const generarNubepalabras = (limite: number = 20) => {
  const palabras: { [key: string]: number } = {};
  
  testimonios.forEach(t => {
    const comentarioLower = t.comentario.toLowerCase();
    const palabrasComentario = comentarioLower
      .split(/\s+/)
      .filter(p => p.length > 4)
      .filter(p => !['pero', 'para', 'desde', 'sobre'].includes(p));
    
    palabrasComentario.forEach(p => {
      palabras[p] = (palabras[p] || 0) + 1;
    });
  });
  
  return Object.entries(palabras)
    .sort((a, b) => b[1] - a[1])
    .slice(0, limite)
    .map(([palabra, frecuencia]) => ({ palabra, frecuencia }));
};

