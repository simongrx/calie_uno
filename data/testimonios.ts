// CÁLCULO DE UTILIDAD
export const calcularUtilidadTestimonio = (testimonioId: string) => {
  const testimonio = obtenerTestimonioPorId(testimonioId);
  if (!testimonio) return 0;
  
  // Fórmula: (rating * 2) + (tiene foto * 1) + (tiene video * 2)
  let utilidad = testimonio.rating * 2;
  if (testimonio.foto) utilidad += 1;
  if (testimonio.video) utilidad += 2;
  
  return utilidad;
};

// ORDENAMIENTO PERSONALIZADO
export const ordenarTestimonios = (
  testimonios: Testimonio[],
  criterio: 'reciente' | 'rating' | 'utilidad' | 'aleatorio'
) => {
  const copia = [...testimonios];
  
  switch (criterio) {
    case 'reciente':
      return copia.sort(
        (a, b) => new Date(b.fecha || '').getTime() - new Date(a.fecha || '').getTime()
      );
    case 'rating':
      return copia.sort((a, b) => b.rating - a.rating);
    case 'utilidad':
      return copia.sort(
        (a, b) => calcularUtilidadTestimonio(b.id) - calcularUtilidadTestimonio(a.id)
      );
    case 'aleatorio':
      return copia.sort(() => Math.random() - 0.5);
    default:
      return copia;
  }
};

