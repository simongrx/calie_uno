// FILTRO AVANZADO
export interface FiltroTestimonios {
  ratingMin?: number;
  ruta?: string;
  pais?: string;
  conFoto?: boolean;
  conVideo?: boolean;
  busqueda?: string;
}

export const filtrarTestimonios = (filtro: FiltroTestimonios) => {
  return testimonios.filter(t => {
    if (filtro.ratingMin && t.rating < filtro.ratingMin) return false;
    if (filtro.ruta && t.rutaVisitada !== filtro.ruta) return false;
    if (filtro.pais && t.pais !== filtro.pais) return false;
    if (filtro.conFoto === true && !t.foto) return false;
    if (filtro.conVideo === true && !t.video) return false;
    if (filtro.busqueda) {
      const busquedaLower = filtro.busqueda.toLowerCase();
      return (
        t.nombre.toLowerCase().includes(busquedaLower) ||
        t.comentario.toLowerCase().includes(busquedaLower) ||
        t.pais.toLowerCase().includes(busquedaLower)
      );
    }
    return true;
  });
};

